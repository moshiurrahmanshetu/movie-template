/**
 * Helper query functions for the client-side catalog
 */
function getMovieBySlug(slug) {
  if (!slug) return null;
  const cleanSlug = String(slug).toLowerCase().trim();
  return MOVIES_DATABASE.find(m => m.slug === cleanSlug) || null;
}

function getMoviesByCategory(categorySlug) {
  if (!categorySlug || categorySlug === 'all') return MOVIES_DATABASE;
  const target = String(categorySlug).toLowerCase().trim();
  return MOVIES_DATABASE.filter(m => {
    const inGenre = m.genre && m.genre.some(g => g.toLowerCase() === target);
    const inCategory = m.category && m.category.toLowerCase() === target;
    return inGenre || inCategory;
  });
}

function getMoviesByLanguage(languageSlug) {
  if (!languageSlug || languageSlug === 'all') return MOVIES_DATABASE;
  const target = String(languageSlug).toLowerCase().trim();
  return MOVIES_DATABASE.filter(m => m.language && m.language.toLowerCase().includes(target));
}

function getLatestMovies(limit = null) {
  const sorted = [...MOVIES_DATABASE].sort((a, b) => new Date(b.releaseDate).getTime() - new Date(a.releaseDate).getTime());
  return limit ? sorted.slice(0, limit) : sorted;
}

function getPopularMovies(limit = null) {
  const sorted = [...MOVIES_DATABASE].sort((a, b) => b.popularity - a.popularity);
  return limit ? sorted.slice(0, limit) : sorted;
}

function getRelatedMovies(currentSlug, limit = 4) {
  const current = getMovieBySlug(currentSlug);
  if (!current) return MOVIES_DATABASE.slice(0, limit);

  const others = MOVIES_DATABASE.filter(m => m.slug !== current.slug);
  
  // Rank similarity: same category/genre + same language
  const scored = others.map(movie => {
    let score = 0;
    if (movie.category === current.category) score += 3;
    const sharedGenres = movie.genre.filter(g => current.genre.includes(g));
    score += sharedGenres.length * 2;
    if (movie.language === current.language) score += 1;
    return { movie, score };
  });

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map(item => item.movie);
}
